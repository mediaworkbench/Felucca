"""A DRUM track's BRAIN pages (firmware/src/dbrain.c): DrumBrain's model as a C header.

assets/drumbrain/model.js is DrumBrain's model as it is (Michael Ganss, github.com/mganss/DrumBrain at 95a7cb4, MIT:
LICENSES/MIT-DrumBrain.txt): for each style (all, house, breaks) and instrument (AC BD SD LT MT HT RS CP CB CY OH CH) a
dictionary context -> {next step: probability}. A context is text over 0 1 2 5 (rest, low, high, flam), "-" between
beats and "^" at the start. DrumBrain looks up the longest end of its text that is a key, up to CONTEXT characters.
Nothing of the model is changed: every context and every continuation kept, the probabilities only rounded (to 1/16
log2, as the ratio to the context's likeliest: the C side's temperature works in log2).

One forward trie per style and instrument (36 tables), its nodes in breadth-first order, a node's children in the order
of DB_SYM. The contexts are not prefix-closed, so a node may be interior: it is on the way to a context and is none
itself. The header, every table const (flash):
  DB_NODE[n]     child mask (bit s: a child on symbol s) | distribution << 6 (0: interior, else DB_DIST[d - 1])
  DB_ROOT[t]     table t's root (style * 12 + instrument); DB_ROOT[36]: the node count
  DB_CK[k]       the children of all the nodes before node 8k (all tables): node n of table t's first child is at
                 t + 1 + DB_CK[n >> 3] + the children of the nodes from 8 (n >> 3) to n - 1
  DB_DIST[d][4]  the weights of 0 1 2 5: round(-16 log2(p / p of the likeliest)), 254 at most; 255: never

  gen_dbrain.py OUT.h [REF.txt]     the header; REF: every context with its exact weights and odds (tests/dbrain_test.c)
"""
import json
import math
import sys
from pathlib import Path

MODEL = Path(__file__).resolve().parent.parent / "assets" / "drumbrain" / "model.js"
STYLES = ["all", "house", "breaks"]
NINST = 12
DB_SYM = "0125-^"        # the model's symbols; the first four are the steps
STEPS = DB_SYM[:4]


def weights(dist):
    top = max(dist.values())
    return tuple(255 if k not in dist else min(254, round(-16 * math.log2(dist[k] / top))) for k in STEPS)


def table_nodes(d):
    """the trie's nodes in breadth-first order: every context and every prefix of one"""
    keys = {""}
    for c in d:
        for i in range(1, len(c) + 1):
            keys.add(c[:i])
    return sorted(keys, key=lambda k: (len(k), [DB_SYM.index(c) for c in k]))


def main():
    text = MODEL.read_text()
    model = json.loads(text[text.index("{"):text.rindex("}") + 1])
    dists = {}
    for st in STYLES:
        assert len(model[st]) == NINST
        for d in model[st]:
            assert "" in d                       # (the lookup always ends)
            for x in d.values():
                assert set(x) <= set(STEPS)
                dists.setdefault(weights(x))
    order = sorted(dists)
    index = {w: i + 1 for i, w in enumerate(order)}
    assert len(order) < 1 << 10

    nodes, roots, ck, seen = [], [], [], 0
    for st in STYLES:
        for d in model[st]:
            keys = table_nodes(d)
            kset = set(keys)
            roots.append(len(nodes))
            for k in keys:
                if len(nodes) % 8 == 0:
                    ck.append(seen)
                mask = sum(1 << i for i, c in enumerate(DB_SYM) if k + c in kset)
                seen += bin(mask).count("1")
                nodes.append(mask | (index[weights(d[k])] if k in d else 0) << 6)
    roots.append(len(nodes))

    def table(ty, name, vals, per=16):
        rows = (", ".join(map(str, vals[i:i + per])) for i in range(0, len(vals), per))
        return f"static const {ty} {name}[] = {{\n" + ",\n".join(rows) + "\n};\n"

    with open(sys.argv[1], "w") as f:
        f.write("/* generated by tools/gen_dbrain.py from assets/drumbrain/model.js (DrumBrain, MIT) */\n")
        f.write(f"#define DB_NTABLE {len(roots) - 1}\n#define DB_NDIST {len(order)}\n")
        f.write(table("uint16_t", "DB_NODE", nodes))
        f.write(table("uint16_t", "DB_ROOT", roots))
        f.write(table("uint16_t", "DB_CK", ck))
        f.write("static const uint8_t DB_DIST[][4] = {\n")
        f.write(",\n".join("{" + ", ".join(map(str, w)) + "}" for w in order))
        f.write("\n};\n")
    if len(sys.argv) > 2:
        with open(sys.argv[2], "w") as f:        # table, context ("." the empty one), weights, odds of 0 1 2 5
            for s, st in enumerate(STYLES):
                for i, d in enumerate(model[st]):
                    for c, x in d.items():
                        w = weights(x)
                        odds = " ".join(f"{x.get(k, 0):.17g}" for k in STEPS)
                        f.write(f"{s * NINST + i} {c or '.'} {w[0]} {w[1]} {w[2]} {w[3]} {odds}\n")
    size = 2 * (len(nodes) + len(roots) + len(ck)) + 4 * len(order)
    print(f"gen_dbrain: {len(nodes)} nodes, {len(order)} distributions, {size} bytes")


if __name__ == "__main__":
    main()
